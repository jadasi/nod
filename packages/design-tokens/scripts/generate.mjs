// Generates every design-system output from tokens.json, icons.json and pixel-font.json.
//
//   pnpm --filter @nod/design-tokens generate
//
// Outputs (all committed, so the web app keeps its no-build-step setup):
//   apps/web/public/tokens.css      themes as CSS custom properties, @font-face, icon + illustration classes
//   apps/web/public/tokens.js       tokens + the pixel font as an ES module (web inbox)
//   apps/web/public/icon.svg        the app icon
//   packages/design-tokens/src/generated.ts   typed tokens, icons, illustrations and font (Android, glasses)
//   packages/design-tokens/icons/*.svg        one crisp SVG per icon and illustration (review, Android)
//
// `outputs()` is pure so the tests can check the committed files are in sync.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const pkg = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const repoRoot = resolve(pkg, '../..');

const read = (f) => JSON.parse(readFileSync(resolve(pkg, f), 'utf8'));
const kebab = (s) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const BANNER = 'Generated by packages/design-tokens/scripts/generate.mjs. Do not edit.';

/**
 * Merges each row's runs of `ink` pixels into one rectangle per run: a compact, crisp path.
 * `ink` is '#' for icons and the base layer of illustrations, '+' for the accent layer.
 */
export function gridPath(rows, ink = '#') {
  let d = '';
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== ink) {
        x++;
        continue;
      }
      let w = 0;
      while (row[x + w] === ink) w++;
      d += `M${x} ${y}h${w}v1h-${w}z`;
      x += w;
    }
  });
  return d;
}

function svg(rows, { fill = 'currentColor', accent, size, background, ink = '#' } = {}) {
  const w = rows[0].length;
  const h = rows.length;
  const dims = size ? ` width="${(size * w) / h}" height="${size}"` : '';
  const bg = background ? `<rect width="${w}" height="${h}" fill="${background}"/>` : '';
  const second = accent ? `<path fill="${accent}" d="${gridPath(rows, '+')}"/>` : '';
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}"${dims} shape-rendering="crispEdges">` +
    `${bg}<path fill="${fill}" d="${gridPath(rows, ink)}"/>${second}</svg>`
  );
}
const dataUri = (s) => `url("data:image/svg+xml,${encodeURIComponent(s)}")`;

function themeVars(theme) {
  const v = [`  color-scheme: ${theme.scheme};`];
  for (const [k, value] of Object.entries(theme.color)) v.push(`  --color-${kebab(k)}: ${value};`);
  v.push(`  --effect-glow: ${theme.effect.glow};`);
  v.push(`  --effect-scanline: ${theme.effect.scanline};`);
  return v.join('\n');
}

function css(tokens, icons) {
  const v = [];
  const add = (name, value) => v.push(`  --${name}: ${value};`);
  add('font-body', tokens.font.body.value);
  add('font-mono', tokens.font.mono.value);
  for (const [k, t] of Object.entries(tokens.type)) {
    add(`type-${k}-size`, `${t.size}px`);
    add(`type-${k}-line`, `${t.lineHeight}px`);
    add(`type-${k}-weight`, t.weight);
    add(`type-${k}-tracking`, `${t.tracking}em`);
  }
  for (const [k, n] of Object.entries(tokens.space)) add(`space-${k}`, `${n}px`);
  for (const [k, n] of Object.entries(tokens.border)) add(`border-${kebab(k)}`, `${n}px`);
  for (const [k, n] of Object.entries(tokens.radius)) add(`radius-${k}`, `${n}px`);
  for (const [k, n] of Object.entries(tokens.size)) add(`size-${kebab(k)}`, `${n}px`);
  for (const k of ['fast', 'base', 'slow']) add(`motion-${k}`, `${tokens.motion[k]}ms`);
  add('motion-easing', tokens.motion.easing);
  add('motion-stepped', tokens.motion.stepped);
  add('effect-scanline-pitch', `${tokens.emphasis.scanlinePitch}px`);
  for (const k of ['sm', 'md', 'lg']) add(`icon-${k}`, `${tokens.icon[k]}px`);
  for (const [name, { rows }] of Object.entries(icons.icons)) {
    add(`icon-${kebab(name)}`, dataUri(svg(rows)));
  }
  for (const [name, { rows }] of Object.entries(icons.illustrations)) {
    add(`illo-${kebab(name)}`, dataUri(svg(rows)));
    add(`illo-${kebab(name)}-accent`, dataUri(svg(rows, { ink: '+' })));
  }
  const classes = Object.keys(icons.icons)
    .map((name) => `.icon-${kebab(name)} {\n  --i: var(--icon-${kebab(name)});\n}`)
    .join('\n');
  const illos = Object.entries(icons.illustrations)
    .map(
      ([name, { rows }]) =>
        `.illo-${kebab(name)} {\n  --illo: var(--illo-${kebab(name)});\n  --illo-accent: var(--illo-${kebab(name)}-accent);\n  aspect-ratio: ${rows[0].length} / ${rows.length};\n}`,
    )
    .join('\n');
  const faces = tokens.font.body.files
    .map((file) => {
      const range = file.includes('latin-ext')
        ? 'U+0100-02BA, U+02BD-02C5, U+02C7-02CC, U+02CE-02D7, U+02DD-02FF, U+1E00-1EFF, U+20A0-20AB, U+20AD-20C0, U+2113, U+2C60-2C7F, U+A720-A7FF'
        : 'U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD';
      return `@font-face {
  font-family: 'Space Grotesk';
  font-style: normal;
  font-weight: 300 700;
  font-display: swap;
  src: url('/fonts/${file}') format('woff2');
  unicode-range: ${range};
}`;
    })
    .join('\n');
  const { dark, light } = tokens.themes;
  return `/* ${BANNER} */
/* ${tokens.font.body.use} License: fonts/OFL.txt */
${faces}

:root {
${v.join('\n')}
}

/* Themes: dark by default, light when the system asks, either when data-theme is set. */
:root,
[data-theme='dark'] {
${themeVars(dark)}
}
@media (prefers-color-scheme: light) {
  :root:not([data-theme='dark']) {
${themeVars(light).replace(/^/gm, '  ')}
  }
}
[data-theme='light'] {
${themeVars(light)}
}

/* Pixel icons: <span class="icon icon-check" aria-hidden="true"></span>. Colour follows currentColor. */
.icon {
  display: inline-block;
  flex: none;
  width: var(--icon-md);
  height: var(--icon-md);
  background-color: currentColor;
  -webkit-mask: var(--i) center / 100% 100% no-repeat;
  mask: var(--i) center / 100% 100% no-repeat;
}
.icon.sm {
  width: var(--icon-sm);
  height: var(--icon-sm);
}
.icon.lg {
  width: var(--icon-lg);
  height: var(--icon-lg);
}
${classes}

/* Pixel illustrations: two inks, the base in currentColor and the highlights in accent green.
   <span class="illo illo-empty" aria-hidden="true"></span>; set a width in whole multiples of the grid. */
.illo {
  position: relative;
  display: inline-block;
  flex: none;
}
.illo::before,
.illo::after {
  content: '';
  position: absolute;
  inset: 0;
  -webkit-mask: var(--illo) center / 100% 100% no-repeat;
  mask: var(--illo) center / 100% 100% no-repeat;
  background-color: currentColor;
}
.illo::after {
  -webkit-mask-image: var(--illo-accent);
  mask-image: var(--illo-accent);
  background-color: var(--color-accent-ink);
}
${illos}
`;
}

function tokensJs(tokens, icons, font) {
  const uses = Object.fromEntries(Object.entries(icons.icons).map(([k, i]) => [kebab(k), i.use]));
  const illos = Object.fromEntries(
    Object.entries(icons.illustrations).map(([k, i]) => [
      kebab(k),
      { use: i.use, width: i.rows[0].length, height: i.rows.length },
    ]),
  );
  return `// ${BANNER}
// Tokens for scripts (the design reference page) and the Nod Pixel 5x7 face, an original
// dot-matrix display font: display only, never running text.
export const TOKENS = ${JSON.stringify(tokens)};
export const ICONS = ${JSON.stringify(uses)};
export const ILLUSTRATIONS = ${JSON.stringify(illos)};
export const HEIGHT = ${font.height};
export const GLYPHS = ${JSON.stringify(font.glyphs)};
`;
}

function ts(tokens, icons, font) {
  const iconOut = Object.fromEntries(
    Object.entries(icons.icons).map(([k, i]) => [
      k,
      { use: i.use, rows: i.rows, path: gridPath(i.rows) },
    ]),
  );
  const illoOut = Object.fromEntries(
    Object.entries(icons.illustrations).map(([k, i]) => [
      k,
      {
        use: i.use,
        width: i.rows[0].length,
        height: i.rows.length,
        rows: i.rows,
        path: gridPath(i.rows),
        accentPath: gridPath(i.rows, '+'),
      },
    ]),
  );
  const app = { use: icons.app.use, rows: icons.app.rows, path: gridPath(icons.app.rows) };
  return `/* ${BANNER} */
export const tokens = ${JSON.stringify(tokens, null, 2)} as const;

/** 12x12 pixel icons. \`path\` is in grid units: draw it in a 12x12 viewBox with crisp edges. */
export const icons = ${JSON.stringify(iconOut, null, 2)} as const;

/** Two-ink pixel illustrations: \`path\` in the text colour, \`accentPath\` in accentInk. */
export const illustrations = ${JSON.stringify(illoOut, null, 2)} as const;

/** The app icon on a 24x24 grid. */
export const appIcon = ${JSON.stringify(app, null, 2)} as const;

export const pixelFont = ${JSON.stringify({ height: font.height, glyphs: font.glyphs }, null, 2)} as const;
`;
}

/** Every generated file, keyed by path relative to the repository root. */
export function outputs() {
  const tokens = read('tokens.json');
  const icons = read('icons.json');
  const font = read('pixel-font.json');
  const dark = tokens.themes.dark.color;
  const files = new Map();
  files.set('apps/web/public/tokens.css', css(tokens, icons));
  files.set('apps/web/public/tokens.js', tokensJs(tokens, icons, font));
  files.set(
    'apps/web/public/icon.svg',
    svg(icons.app.rows, { fill: dark.accent, background: dark.bg }) + '\n',
  );
  files.set('packages/design-tokens/src/generated.ts', ts(tokens, icons, font));
  for (const [name, { rows }] of Object.entries(icons.icons)) {
    files.set(`packages/design-tokens/icons/${kebab(name)}.svg`, svg(rows, { size: 24 }) + '\n');
  }
  for (const [name, { rows }] of Object.entries(icons.illustrations)) {
    files.set(
      `packages/design-tokens/icons/illo-${kebab(name)}.svg`,
      svg(rows, { size: rows.length * 4, accent: dark.accentInk }) + '\n',
    );
  }
  return files;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  for (const [rel, content] of outputs()) {
    const file = resolve(repoRoot, rel);
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, content);
  }
  process.stdout.write(`wrote ${outputs().size} files\n`);
}
